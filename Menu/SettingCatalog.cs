namespace RonMenu;

internal sealed class FeatureSetting
{
    public FeatureSetting(string category, string title, string description, string key, string type = "bool", double minimum = 0, double maximum = 1, double step = 1)
    {
        Category = category; Title = title; Description = description; Key = key; Type = type; Minimum = minimum; Maximum = maximum; Step = step;
    }
    public string Category { get; }
    public string Title { get; }
    public string Description { get; }
    public string Key { get; }
    public string Type { get; }
    public double Minimum { get; }
    public double Maximum { get; }
    public double Step { get; }
}

